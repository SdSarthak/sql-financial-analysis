CREATE TABLE client_data (
    age INT,
    job VARCHAR(50),
    marital VARCHAR(20),
    education VARCHAR(20),
    default_status VARCHAR(10),
    balance NUMERIC,
    housing_loan VARCHAR(10),
    personal_loan VARCHAR(10),
    contact VARCHAR(20),
    last_contact_day INT,
    last_contact_month VARCHAR(10),
    last_contact_duration INT,
    campaign_contacts INT,
    days_since_last_contact INT,
    previous_contacts INT,
    previous_outcome VARCHAR(20),
    subscribed VARCHAR(10)
);
